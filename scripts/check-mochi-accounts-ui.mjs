import assert from 'node:assert/strict'
import {resolve} from 'node:path'

// Synthetic host only. Uses the production account, room and notification views.
export async function checkMochiAccounts(browser,output){
 for(const width of [320,390,900]){
  const page=await browser.newPage({viewport:{width,height:850},isMobile:width<900,hasTouch:width<900})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto(new URL('file:///'+resolve(output,'index.html').replaceAll('\\','/')).href)
  const settled=()=>page.waitForFunction(()=>!window.__mochiDemo.view.busy)
  const fits=async()=>assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Account screens fit '+width+'px')
  await page.evaluate(async()=>{
   const {service,view}=window.__mochiDemo
   service.resolvePhone=async(_,p)=>[p.chatId,p.characterId,p.deviceOwnerActorId].map(encodeURIComponent).join('::')
   let room=await service.create('synthetic-user',{title:'Legacy chat to preserve',characterIds:['character1'],persona:{source:'manual',name:'Original saved identity',description:'Keep this exact snapshot'}})
   room=await service.update('synthetic-user',{roomId:room.id,revision:room.revision,title:room.title,characterIds:room.characterIds,settings:{...room.settings,autoReply:false}})
   await service.message('synthetic-user',{roomId:room.id,revision:room.revision,requestId:'legacy_history',content:'Keep my legacy history'})
   window.__legacyBefore=await service.read('synthetic-user',room.id)
   view.open({chatId:'demo_chat',characterId:'character1',deviceOwnerActorId:'owner_a'})
  })
  await page.getByRole('button',{name:'Create Mochi account',exact:true}).waitFor();await settled();await fits()
  await page.screenshot({path:resolve(output,'accounts-picker-'+width+'.png')})
  const name='Alexandria Celestina Long Fictional Profile Name For Narrow Screens'
  await page.getByRole('button',{name:'Create Mochi account',exact:true}).click()
  await page.getByLabel('Profile display name',{exact:true}).fill(name)
  await page.getByLabel('Profile username',{exact:true}).fill('@cozy_alexandria')
  await page.getByLabel('Profile identity description',{exact:true}).fill('Synthetic account identity')
  await fits();await page.screenshot({path:resolve(output,'accounts-profile-'+width+'.png')})
  await page.getByRole('button',{name:'Save profile',exact:true}).click();await settled()
  await page.getByRole('button',{name:'New room',exact:true}).waitFor()
  const firstId=await page.evaluate(()=>window.__mochiDemo.view.state.accountId)
  await page.getByRole('button',{name:'New room',exact:true}).click()
  await page.getByLabel('Room name',{exact:true}).fill('A very long account room name with graceful wrapping on small screens')
  await page.getByRole('button',{name:'Long character name for mobile wrapping',exact:true}).click()
  assert.equal(await page.getByLabel('Your name',{exact:true}).count(),0,'Account and chat identity forms are separate')
  await page.getByRole('button',{name:'Create room',exact:true}).click();await settled()
  await page.getByLabel('Room options',{exact:true}).click(); await page.getByRole('button',{name:'Settings',exact:true}).click(); for(const summary of await page.locator('details.mochi-settings-section > summary').all()) if((await summary.locator('..').getAttribute('open'))===null) await summary.click()
  await page.getByLabel('Generation connection',{exact:true}).selectOption('test')
  await page.getByLabel('Response mode',{exact:true}).selectOption('manual')
  await page.getByRole('button',{name:'Save settings',exact:true}).click();await settled()
  await page.getByLabel('Message',{exact:true}).fill('Private first-account history');await page.getByLabel('Message',{exact:true}).press('Enter');await settled()
  assert.equal(await page.locator('.mochi-message[data-role=user] .mochi-message-name').textContent(),'You')
  await page.getByLabel('Message',{exact:true}).press('Enter');await page.locator('.mochi-message[data-role=assistant]').waitFor();await settled()
  await page.getByLabel('Room options',{exact:true}).click(); await page.getByRole('button',{name:'Settings',exact:true}).click(); for(const summary of await page.locator('details.mochi-settings-section > summary').all()) if((await summary.locator('..').getAttribute('open'))===null) await summary.click()
  await page.getByLabel('Response mode',{exact:true}).selectOption('instant')
  await page.getByRole('button',{name:'Save settings',exact:true}).click();await settled()
  assert.equal(await page.evaluate(()=>window.__mochiDemo.view.state.backgroundEnabled),false)
  assert.equal(await page.evaluate(()=>window.__mochiDemo.view.state.rooms[0].background?.enabled||false),false)
  await page.getByLabel('Message',{exact:true}).fill('Instant automatic reply without background autonomy')
  await page.getByRole('button',{name:'Send',exact:true}).click()
  await page.waitForFunction(()=>window.__mochiDemo.view.state.rooms[0].messages.length===4&&!window.__mochiDemo.view.busy)
  await page.getByLabel('Message',{exact:true}).press('Enter')
  await page.waitForFunction(()=>window.__mochiDemo.view.state.rooms[0].messages.length===5&&!window.__mochiDemo.view.busy)
  await page.getByRole('button',{name:'Room inbox',exact:true}).click()
  await page.getByRole('button',{name:'Account settings',exact:true}).click();await settled()
  await page.getByLabel('Profile username',{exact:true}).fill('@changed_name')
  await page.getByRole('button',{name:'Save profile',exact:true}).click();await settled()
  await page.getByRole('button',{name:'Back',exact:true}).click()
  await page.getByRole('button',{name:'Switch Mochi account',exact:true}).click();await settled()
  await page.getByLabel('Mochi startup preference',{exact:true}).selectOption('picker');await settled()
  await page.getByRole('button',{name:'Create Mochi account',exact:true}).click()
  await page.getByLabel('Profile display name',{exact:true}).fill('Second fictional account')
  await page.getByRole('button',{name:'Save profile',exact:true}).click();await settled()
  await page.waitForFunction(id=>!window.__mochiDemo.view.busy&&window.__mochiDemo.view.state?.accountId&&window.__mochiDemo.view.state.accountId!==id,firstId)
  assert.equal(await page.locator('button.mochi-card').count(),0,'Second account cannot see first account chats: '+JSON.stringify(await page.locator('button.mochi-card').evaluateAll(ns=>ns.map(n=>({tag:n.tagName,label:n.getAttribute('aria-label'),text:n.textContent})))) )
  await page.evaluate(async id=>{
   const {service,scheduler,view}=window.__mochiDemo
   const room=(await service.state('synthetic-user',id)).rooms[0]
   await scheduler.configure('synthetic-user',true)
   await service.configureScheduledRoom('synthetic-user',{accountId:id,roomId:room.id,revision:room.revision,enabled:true})
   await service.schedule('synthetic-user',{accountId:id,roomId:room.id,revision:room.revision,occurrenceId:'offline_account_notice',dueAt:Date.now()},Date.now())
   await scheduler.tick()
   if(view.state.notifications.length)throw Error('Scheduled notification leaked into another account')
   window.__scheduledRoom=room.id
  },firstId)
  assert.equal(await page.locator('.mochi-unread-count').count(),0,'Another account scheduled reply does not leak a counter')
  await page.getByRole('button',{name:'Switch Mochi account',exact:true}).click();await settled();await fits()
  await page.screenshot({path:resolve(output,'accounts-multiple-'+width+'.png')})
  await page.getByRole('button',{name:'Unassigned legacy chats',exact:true}).click();await settled()
  await page.getByRole('button',{name:/Legacy chat to preserve/}).click()
  await page.getByLabel('Room options',{exact:true}).click(); await page.getByRole('button',{name:'Settings',exact:true}).click(); for(const summary of await page.locator('details.mochi-settings-section > summary').all()) if((await summary.locator('..').getAttribute('open'))===null) await summary.click()
  await page.getByLabel('Assign chat to Mochi account',{exact:true}).selectOption(firstId)
  assert.equal(await page.getByRole('button',{name:'Assign legacy chat',exact:true}).isDisabled(),true)
  await page.getByLabel('Keep saved persona and all chat data',{exact:true}).check()
  await fits();await page.screenshot({path:resolve(output,'accounts-assignment-'+width+'.png')})
  await page.getByRole('button',{name:'Assign legacy chat',exact:true}).click();await settled()
  assert.equal(await page.getByRole('button',{name:/Legacy chat to preserve/}).count(),0)
  await page.getByRole('button',{name:'Switch Mochi account',exact:true}).click();await settled()
  await page.getByRole('button',{name:'Use Mochi account '+name,exact:true}).click();await settled()
  assert.equal(await page.locator('button.mochi-card').count(),2)
  assert.equal(await page.locator('.mochi-unread-count').textContent(),'1','Owning account sees its scheduled unread notification')
  await page.getByRole('button',{name:'Mochi notifications',exact:true}).click()
  await page.screenshot({path:resolve(output,'accounts-notifications-'+width+'.png')})
  const preservedMessages=await page.evaluate(async id=>JSON.stringify((await window.__mochiDemo.service.read('synthetic-user',window.__scheduledRoom,id)).messages),firstId)
  await page.getByRole('button',{name:'Clear all',exact:true}).click()
  await page.getByRole('button',{name:'Confirm clear all',exact:true}).click();await settled()
  assert.equal(await page.locator('.mochi-unread-count').count(),0)
  assert.equal(await page.evaluate(async id=>JSON.stringify((await window.__mochiDemo.service.read('synthetic-user',window.__scheduledRoom,id)).messages),firstId),preservedMessages,'Account notification clearing preserves scheduled history')
  await page.getByRole('button',{name:'Back to rooms',exact:true}).click()
  await page.getByRole('button',{name:/Legacy chat to preserve/}).click()
  assert.equal(await page.locator('.mochi-bubble').textContent(),'Keep my legacy history')
  await page.evaluate(async id=>{const {service}=window.__mochiDemo,before=window.__legacyBefore,after=await service.read('synthetic-user',before.id,id);if(JSON.stringify(after.messages)!==JSON.stringify(before.messages)||JSON.stringify(after.persona)!==JSON.stringify(before.persona)||JSON.stringify(after.receipts)!==JSON.stringify(before.receipts))throw Error('Legacy assignment changed saved history')},firstId)
  await page.getByRole('button',{name:'Room inbox',exact:true}).click()
  await page.getByRole('button',{name:'Account settings',exact:true}).click();await settled()
  await page.getByRole('button',{name:'Archive profile',exact:true}).click()
  await page.getByRole('button',{name:'Cancel',exact:true}).click()
  assert.equal(await page.getByLabel('Profile display name',{exact:true}).inputValue(),name)
  await page.getByRole('button',{name:'Archive profile',exact:true}).click()
  await page.getByRole('button',{name:'Confirm archive and preserve chats',exact:true}).click();await settled()
  assert.equal(await page.getByRole('button',{name:'Use Mochi account '+name,exact:true}).count(),0)
  await page.getByRole('button',{name:'Manage Mochi profiles',exact:true}).click()
  await page.getByRole('button',{name:'Restore '+name,exact:true}).click()
  await page.getByRole('button',{name:'Confirm restore profile',exact:true}).click();await settled()
  await page.getByRole('button',{name:'Back',exact:true}).click()
  assert.equal(await page.getByRole('button',{name:'Use Mochi account '+name,exact:true}).count(),1)
  await page.evaluate(()=>window.__mochiDemo.view.open({chatId:'demo_chat',characterId:'character1',deviceOwnerActorId:'owner_a'}));await settled()
  assert.equal(await page.getByRole('button',{name:'Use Mochi account '+name,exact:true}).count(),1,'Always-ask startup remains a picker')
  await page.getByLabel('Mochi startup preference',{exact:true}).selectOption('last-used');await settled()
  await page.getByRole('button',{name:'Use Mochi account '+name,exact:true}).click();await settled()
  await page.evaluate(()=>window.__mochiDemo.view.open({chatId:'demo_chat',characterId:'character1',deviceOwnerActorId:'owner_a'}));await settled()
  assert.equal(await page.locator('button.mochi-card').count(),2,'Last-used startup restores the owning account')
  await page.evaluate(()=>window.__mochiDemo.view.open({chatId:'demo_chat',characterId:'character1',deviceOwnerActorId:'owner_b'}));await settled()
  assert.equal(await page.getByRole('button',{name:'Use Mochi account '+name,exact:true}).count(),1,'A second phone has its own selection')
  await fits();assert.deepEqual(errors,[]);await page.close()
 }
 console.log('Mochi account Chromium checks passed at 320px, 390px and 900px.')
}
